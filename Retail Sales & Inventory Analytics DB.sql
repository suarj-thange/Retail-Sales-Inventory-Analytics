-- 86. Calculate the discount amount for each sale item
SELECT SALEITEMID,SALEID,PRODUCTID,QUANTITY,UNITPRICE,DISCOUNTPERCENTAGE,
    ROUND(QUANTITY * UNITPRICE * DISCOUNTPERCENTAGE / 100,2) AS DISCOUNT_AMOUNT
FROM SALEITEMS;

-- 87. Calculate the net amount for each sale item after discount
SELECT SALEITEMID,SALEID,PRODUCTID,
    ROUND(QUANTITY * UNITPRICE *(1 - DISCOUNTPERCENTAGE / 100),2) AS NET_AMOUNT
FROM SALEITEMS;

-- 88. Calculate estimated gross profit for each sale item
SELECT SI.SALEITEMID,SI.SALEID,P.PRODUCTNAME,SI.QUANTITY,SI.UNITPRICE,P.COSTPRICE,SI.DISCOUNTPERCENTAGE,
    ROUND(SI.QUANTITY *(SI.UNITPRICE * (1 - SI.DISCOUNTPERCENTAGE / 100)- P.COSTPRICE),2) AS ESTIMATED_GROSS_PROFIT
FROM SALEITEMS SI
JOIN PRODUCTS P
    ON SI.PRODUCTID = P.PRODUCTID;

