SELECT
    C.CUSTOMERID,CONCAT(C.FIRSTNAME, ' ', C.LASTNAME) AS CUSTOMER_NAME,
    ROUND(SUM(SI.QUANTITY * SI.UNITPRICE *(1 - SI.DISCOUNTPERCENTAGE / 100)), 2) AS TOTAL_SPENDING
FROM CUSTOMERS C
JOIN SALES S ON C.CUSTOMERID = S.CUSTOMERID
JOIN SALEITEMS SI ON S.SALEID = SI.SALEID
WHERE S.SALESTATUS = 'COMPLETED'
GROUP BY C.CUSTOMERID, C.FIRSTNAME, C.LASTNAME
