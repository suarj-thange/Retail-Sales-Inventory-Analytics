												-- 1. CUSTOMERS TABLE
CREATE TABLE CUSTOMERS (
    CUSTOMERID INT PRIMARY KEY,
    FIRSTNAME VARCHAR(50) NOT NULL,
    LASTNAME VARCHAR(50) NOT NULL,
    EMAIL VARCHAR(100) UNIQUE,
    PHONE VARCHAR(15),
    CITY VARCHAR(50),
    REGISTRATIONDATE DATE NOT NULL
);
                                                       -- 2. PRODUCTS TABLE
CREATE TABLE PRODUCTS (
    PRODUCTID INT PRIMARY KEY,
    PRODUCTNAME VARCHAR(100) NOT NULL,
    CATEGORY VARCHAR(50) NOT NULL,
    SUPPLIERNAME VARCHAR(100),
    COSTPRICE DECIMAL(10,2) NOT NULL,
    SELLINGPRICE DECIMAL(10,2) NOT NULL,
    STOCKQUANTITY INT NOT NULL DEFAULT 0,
    REORDERLEVEL INT NOT NULL DEFAULT 5,
    CHECK (COSTPRICE > 0),
    CHECK (SELLINGPRICE > 0),
    CHECK (STOCKQUANTITY >= 0),
    CHECK (REORDERLEVEL >= 0)
);
                                                              -- 3. STORES TABLE
CREATE TABLE STORES (
    STOREID INT PRIMARY KEY,
    STORENAME VARCHAR(100) NOT NULL,
    CITY VARCHAR(50) NOT NULL,
    STATE VARCHAR(50) NOT NULL
);
                                                                  -- 4. SALES TABLE
CREATE TABLE SALES (
    SALEID INT PRIMARY KEY,
    CUSTOMERID INT,
    STOREID INT NOT NULL,
    SALEDATE DATE NOT NULL,
    SALESTATUS VARCHAR(20) NOT NULL DEFAULT 'COMPLETED',
    PAYMENTMETHOD VARCHAR(30) NOT NULL,
    FOREIGN KEY (CUSTOMERID)
        REFERENCES CUSTOMERS(CUSTOMERID),
    FOREIGN KEY (STOREID)
        REFERENCES STORES(STOREID),
    CHECK (SALESTATUS IN ('COMPLETED', 'CANCELLED', 'RETURNED')),
    CHECK (PAYMENTMETHOD IN ('CASH', 'CARD', 'UPI', 'NET BANKING'))
);
                                                                      -- 5. SALEITEMS TABLE
CREATE TABLE SALEITEMS (
    SALEITEMID INT PRIMARY KEY,
    SALEID INT NOT NULL,
    PRODUCTID INT NOT NULL,
    QUANTITY INT NOT NULL,
    UNITPRICE DECIMAL(10,2) NOT NULL,
    DISCOUNTPERCENTAGE DECIMAL(5,2) NOT NULL DEFAULT 0,
    FOREIGN KEY (SALEID)
        REFERENCES SALES(SALEID),
    FOREIGN KEY (PRODUCTID)
        REFERENCES PRODUCTS(PRODUCTID),
    CHECK (QUANTITY > 0),
    CHECK (UNITPRICE > 0),
    CHECK (DISCOUNTPERCENTAGE BETWEEN 0 AND 100)
);
                                                                    -- 6. PURCHASEORDERS TABLE
CREATE TABLE PURCHASEORDERS (
    PURCHASEORDERID INT PRIMARY KEY,
    PRODUCTID INT NOT NULL,
    ORDERDATE DATE NOT NULL,
    EXPECTEDDATE DATE,
    RECEIVEDDATE DATE,
    QUANTITYORDERED INT NOT NULL,
    QUANTITYRECEIVED INT NOT NULL DEFAULT 0,
    PURCHASESTATUS VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    FOREIGN KEY (PRODUCTID)
        REFERENCES PRODUCTS(PRODUCTID),
    CHECK (QUANTITYORDERED > 0),
    CHECK (QUANTITYRECEIVED >= 0),
    CHECK (QUANTITYRECEIVED <= QUANTITYORDERED),
    CHECK (PURCHASESTATUS IN
        ('PENDING', 'PARTIALLY RECEIVED', 'RECEIVED', 'CANCELLED'))
);

