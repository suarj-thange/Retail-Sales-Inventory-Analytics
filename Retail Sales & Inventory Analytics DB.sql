-- Q193. Create a category-performance view with product count,
-- quantity sold and net revenue from completed sales.
CREATE OR REPLACE VIEW VW_CATEGORY_PERFORMANCE AS
SELECT C.CATEGORYID,C.CATEGORYNAME,
    COUNT(DISTINCT P.PRODUCTID) AS PRODUCT_COUNT,
    COALESCE(SUM(CASE
            WHEN S.SALESTATUS = 'COMPLETED' THEN SI.QUANTITY
            ELSE 0
        END), 0) AS QUANTITY_SOLD,
    ROUND(COALESCE(SUM(
	CASE
            WHEN S.SALESTATUS = 'COMPLETED'
            THEN SI.QUANTITY * SI.UNITPRICE *
                 (1 - SI.DISCOUNTPERCENTAGE / 100)
            ELSE 0
        END), 0), 2) AS NET_REVENUE
FROM CATEGORIES C
LEFT JOIN PRODUCTS P ON C.CATEGORYID = P.CATEGORYID
LEFT JOIN SALEITEMS SI ON P.PRODUCTID = SI.PRODUCTID
LEFT JOIN SALES S ON SI.SALEID = S.SALEID
GROUP BY C.CATEGORYID, C.CATEGORYNAME;


